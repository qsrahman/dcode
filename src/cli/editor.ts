import { spawn } from 'node:child_process'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

// The user's configured editor, following the long-standing Unix convention
// that $VISUAL (the full-screen editor) takes precedence over $EDITOR (the
// line-editor fallback). Returns undefined when neither is set, so the caller
// can show a proper message rather than guessing at a default that may not be
// installed.
export function resolveEditor(
  env: NodeJS.ProcessEnv = process.env,
): string | undefined {
  const editor = (env.VISUAL ?? env.EDITOR ?? '').trim()
  return editor || undefined
}

export const NO_EDITOR_MESSAGE =
  'no editor configured — set $VISUAL or $EDITOR to compose a prompt, e.g.\n' +
  "  export VISUAL='code --wait'   # or:  export EDITOR=vim\n" +
  'then reopen dcode (or re-run the export in this shell) and try /edit again'

// Open the user's editor on a fresh temp file, wait for it to close, and return
// the file's contents. Returns null when no editor is configured. Internal
// newlines are preserved (that's the point — a multi-line prompt becomes one
// message); the caller trims surrounding whitespace.
//
// The caller must pause any readline interface that owns stdin before calling
// this: the editor is spawned with inherited stdio and needs the terminal to
// itself, and two readers on the same tty fight over input.
export async function openInEditor(
  opts: { seed?: string; env?: NodeJS.ProcessEnv } = {},
): Promise<string | null> {
  const editor = resolveEditor(opts.env)
  if (!editor) return null
  const dir = await mkdtemp(join(tmpdir(), 'dcode-edit-'))
  const file = join(dir, 'PROMPT.md')
  try {
    await writeFile(file, opts.seed ?? '')
    await runEditor(editor, file)
    return await readFile(file, 'utf8')
  } finally {
    // Best-effort cleanup; a leftover temp file must never break the REPL.
    await rm(dir, { recursive: true, force: true }).catch(() => {})
  }
}

function runEditor(editor: string, file: string): Promise<void> {
  return new Promise((resolve, reject) => {
    // shell:true so an $EDITOR carrying its own arguments ("code --wait",
    // "emacsclient -c") is honored the way it is everywhere else; the temp path
    // (generated by mkdtemp, no user input) is quoted for the shell. Editors
    // that fork must include their own wait flag in $EDITOR — the same
    // requirement git imposes.
    const child = spawn(`${editor} "${file}"`, {
      stdio: 'inherit',
      shell: true,
    })
    child.on('error', reject)
    child.on('exit', (code, signal) => {
      if (signal) reject(new Error(`editor terminated by signal ${signal}`))
      else if (code) reject(new Error(`editor exited with code ${code}`))
      else resolve()
    })
  })
}
